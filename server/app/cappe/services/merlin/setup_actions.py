def _validate_create_page(payload: dict[str, Any]) -> tuple[Optional[dict[str, Any]], Optional[str]]:
    if not isinstance(payload, dict):
        return None, "invalid payload"
    title = payload.get("title")
    if not isinstance(title, str) or not (1 <= len(title.strip()) <= 255):
        return None, "'title' must be 1-255 characters"
    preset = payload.get("preset")
    if preset is not None and preset not in SETUP_PAGE_PRESETS:
        return None, f"unknown preset '{preset}' — expected one of: {', '.join(sorted(SETUP_PAGE_PRESETS))}"
    blocks: Optional[list[dict[str, Any]]] = None
    if preset is None:
        blocks, err = _validate_blocks(payload.get("blocks"))
        if err:
            return None, err
    return {"title": title.strip(), "preset": preset, "blocks": blocks}, None


def _summary_create_page(payload: dict[str, Any]) -> str:
    if payload.get("preset"):
        return f'Create a "{payload["title"]}" page using the {payload["preset"]} layout'
    n = len(payload.get("blocks") or [])
    return f'Create a "{payload["title"]}" page with {n} section{"s" if n != 1 else ""}'


async def _execute_create_page(conn, site: dict[str, Any], account: Any, payload: dict[str, Any]) -> dict[str, Any]:
    site_id = site["id"]
    base = slugify(payload["title"])
    slug = base
    n = 1
    while await conn.fetchval(
        "SELECT 1 FROM cappe_pages WHERE site_id = $1 AND slug = $2", site_id, slug
    ):
        n += 1
        slug = f"{base}-{n}"

    preset_key = payload.get("preset")
    if preset_key:
        blocks = deepcopy(SETUP_PAGE_PRESETS[preset_key]["blocks"])
    else:
        blocks = payload.get("blocks") or []

    sort_order = await conn.fetchval(
        "SELECT COALESCE(MAX(sort_order), -1) + 1 FROM cappe_pages WHERE site_id = $1", site_id
    )
    row = await conn.fetchrow(
        """INSERT INTO cappe_pages (site_id, title, slug, content, sort_order, status)
           VALUES ($1, $2, $3, $4, $5, 'draft')
           RETURNING id, title, slug""",
        site_id, payload["title"], slug, json.dumps({"blocks": blocks}), sort_order,
    )
    return {"page_id": str(row["id"]), "title": row["title"], "slug": row["slug"]}


class SetupActionError(Exception):
    """Raised by an action's `execute` for a referential failure discovered
    only at execute time (e.g. the target page was deleted after staging).
    Caught by `execute_setup_action` and turned into a `blocked` outcome —
    never a raw 500 to the panel."""


# ---------------------------------------------------------------------------
# add_blocks — append pre-built sections to an EXISTING page. The sanctioned
# exception to client-state-is-truth: the dashboard has no open editor for
# these ops to fold onto, so this writes `cappe_pages.content` directly, the
# same table the page editor's own PUT persists to.
# ---------------------------------------------------------------------------

def _validate_add_blocks(payload: dict[str, Any]) -> tuple[Optional[dict[str, Any]], Optional[str]]:
    if not isinstance(payload, dict):
        return None, "invalid payload"
    page_id = payload.get("page_id")
    if not isinstance(page_id, str):
        return None, "'page_id' is required"
    try:
        UUID(page_id)
    except (ValueError, AttributeError, TypeError):
        return None, "'page_id' must be a valid id"
    blocks, err = _validate_blocks(payload.get("blocks"))
    if err or not blocks:
        return None, err or "'blocks' must be a non-empty list"
    at = payload.get("at")
    if at is not None and (not isinstance(at, int) or isinstance(at, bool) or at < 0):
        return None, "'at' must be a non-negative index"
    return {"page_id": page_id, "blocks": blocks, "at": at}, None


def _summary_add_blocks(payload: dict[str, Any]) -> str:
    types = ", ".join(b["type"] for b in payload["blocks"])
    n = len(payload["blocks"])
    return f"Add {n} section{'s' if n != 1 else ''} to the page ({types})"


async def _execute_add_blocks(conn, site: dict[str, Any], account: Any, payload: dict[str, Any]) -> dict[str, Any]:
    page_id = UUID(payload["page_id"])
    row = await conn.fetchrow(
        "SELECT content FROM cappe_pages WHERE id = $1 AND site_id = $2 FOR UPDATE",
        page_id, site["id"],
    )
    if row is None:
        raise SetupActionError("That page doesn't exist anymore.")
    content = loads(row["content"])
    existing = content.get("blocks") if isinstance(content.get("blocks"), list) else []
    at = payload.get("at")
    insert_at = len(existing) if at is None else min(max(at, 0), len(existing))
    content["blocks"] = existing[:insert_at] + payload["blocks"] + existing[insert_at:]
    await conn.execute(
        "UPDATE cappe_pages SET content = $2, updated_at = NOW() WHERE id = $1",
        page_id, json.dumps(content),
    )
    return {"page_id": str(page_id), "added": len(payload["blocks"])}


