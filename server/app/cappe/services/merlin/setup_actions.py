_FULFILLMENTS = frozenset({"physical", "digital", "service", "booking"})


def _validate_create_product(payload: dict[str, Any]) -> tuple[Optional[dict[str, Any]], Optional[str]]:
    if not isinstance(payload, dict):
        return None, "invalid payload"
    name = payload.get("name")
    if not isinstance(name, str) or not (1 <= len(name.strip()) <= 255):
        return None, "'name' must be 1-255 characters"
    fulfillment = payload.get("fulfillment", "physical")
    if fulfillment not in _FULFILLMENTS:
        return None, "'fulfillment' must be one of: physical, digital, service, booking"
    price_cents = payload.get("price_cents", 0)
    if not isinstance(price_cents, int) or isinstance(price_cents, bool) or price_cents < 0:
        return None, "'price_cents' must be a non-negative integer (cents)"
    description = payload.get("description")
    if description is not None and not isinstance(description, str):
        return None, "'description' must be text"
    digital_file_url = payload.get("digital_file_url")
    if digital_file_url is not None and not isinstance(digital_file_url, str):
        return None, "'digital_file_url' must be text"
    category = payload.get("category")
    if category is not None and (not isinstance(category, str) or len(category) > 120):
        return None, "'category' must be at most 120 characters"
    return {
        "name": name.strip(), "fulfillment": fulfillment, "price_cents": price_cents,
        "description": description, "digital_file_url": digital_file_url, "category": category,
    }, None


def _gate_create_product(payload: dict[str, Any], entitlements: Entitlements, plan: str) -> Optional[str]:
    fulfillment = payload.get("fulfillment", "physical")
    if fulfillment in entitlements.allowed_fulfillment:
        return None
    allowed = ", ".join(sorted(entitlements.allowed_fulfillment)) or "nothing yet"
    return (
        f"Your {entitlements.plan_name} plan can only sell: {allowed}. "
        "Want to set this up as one of those instead, or upgrade first?"
    )


def _summary_create_product(payload: dict[str, Any]) -> str:
    price = f"${payload['price_cents'] / 100:.2f}" if payload["price_cents"] else "free"
    return f'Sell "{payload["name"]}" ({payload["fulfillment"]}, {price})'


async def _execute_create_product(conn, site: dict[str, Any], account: Any, payload: dict[str, Any]) -> dict[str, Any]:
    # A digital good with no file yet would be a sale with nothing to deliver
    # — created as a draft so it can't be bought until the seller finishes it
    # in Shop. Everything else is safe to activate straight from chat.
    status_ = "draft" if payload["fulfillment"] == "digital" and not payload.get("digital_file_url") else "active"
    row = await conn.fetchrow(
        """INSERT INTO cappe_products
               (site_id, name, description, price_cents, status, fulfillment, digital_file_url, category)
           VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
           RETURNING id, name, status, fulfillment""",
        site["id"], payload["name"], payload.get("description"), payload["price_cents"],
        status_, payload["fulfillment"], payload.get("digital_file_url"), payload.get("category"),
    )
    await refresh_site_search(conn, site["id"])
    return {"product_id": str(row["id"]), "name": row["name"], "status": row["status"]}


