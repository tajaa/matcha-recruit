"""Setup-concierge action registry (migration zzzzcappe27).

The dashboard Merlin panel is confirm-first: unlike the page editor's ops
(which fold onto client state and never touch the DB until Save), everything
here is a real server-row write — a new page, a product, a promo banner. The
model never writes directly; it PROPOSES via `stage_action`, the entry lands
in the setup conversation's `staged_actions` JSONB column with
`status='proposed'`, and only an explicit later confirmation (chat or a REST
click) runs `execute_setup_action`. This is the same plan-then-approve shape
as matcha Huume's `evaluate_huume_action`, reimplemented from scratch here —
cappe is a parallel stack and must not import matcha code.

Each `SetupActionSpec` mirrors the `MerlinOp` registry-as-data pattern in
`.ops` (validate + a human summary + prompt text all live on one entry, so
the prompt can't drift from what's actually enforced), with one addition:
`gate` takes the NORMALIZED PAYLOAD too, not just plan/entitlements — a
`create_product` proposal's entitlement check depends on the fulfillment kind
the model is actually asking for, not just the account's plan.

Two-phase evaluation, both pure/DB-free (`evaluate_setup_stage`,
`evaluate_setup_execute`) so they're unit-testable without a database and so
the SAME entitlement message a user sees at stage time ("your plan can only
sell X") is generated by the same code path that authoritatively re-checks it
at execute time — one function, not two copies that can drift.

Cache invalidation and conversation persistence are deliberately NOT done
here: `execute_setup_action` only writes the row this action is about.
Callers (routes/merlin_setup.py, setup_agent.py) own `invalidate_render_cache`
(a routes/-layer function — services/ must never import routes/) and
`store.mutate_staged_actions` (the row-locked queue write).
"""
