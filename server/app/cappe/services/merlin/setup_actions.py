# ---------------------------------------------------------------------------
# Evaluation — pure, DB-free. See module docstring for why stage/execute
# share one gate function per action instead of two hand-written copies.
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Verdict:
    kind: Literal["stage", "blocked", "invalid", "proceed", "refuse"]
    message: str = ""
    # Populated only for kind == "stage": the validated/normalized payload to
    # actually persist (never the model's raw, unfiltered one).
    payload: Optional[dict[str, Any]] = None


def evaluate_setup_stage(
    action_type: str, payload: Any, *, entitlements: Entitlements, plan: str
) -> Verdict:
    """Should a newly-proposed action be staged, or refused outright?"""
    spec = SETUP_ACTIONS_BY_NAME.get(action_type)
    if spec is None:
        return Verdict("invalid", f"unknown action type '{action_type}' — expected one of: {', '.join(sorted(SETUP_ACTIONS_BY_NAME))}")
    normalized, error = spec.validate(payload if isinstance(payload, dict) else {})
    if error:
        return Verdict("invalid", error)
    blocked = spec.gate(normalized, entitlements, plan)
    if blocked:
        return Verdict("blocked", blocked)
    return Verdict("stage", spec.summary(normalized), payload=normalized)


def evaluate_setup_execute(
    entry: dict[str, Any], *, entitlements: Entitlements, plan: str, this_turn_staged_ids
) -> Verdict:
    """May this already-staged entry run now?

    Confirm-first, structurally: `this_turn_staged_ids` is the set of entry
    ids the CURRENT turn itself just staged (tracked by the caller's tool
    loop, empty for the REST approve button) — an id in it is refused, so the
    model can't stage-then-immediately-confirm inside one turn no matter what
    it's told to do. Idempotent: any status other than 'proposed' refuses.
    """
    entry_id = entry.get("id")
    if entry_id in this_turn_staged_ids:
        return Verdict("refuse", "That was just proposed — confirm it on a later message, not the same turn it was staged in.")
    status_ = entry.get("status")
    if status_ != "proposed":
        return Verdict("refuse", f"That action is already {status_} and can't be run again.")
    spec = SETUP_ACTIONS_BY_NAME.get(entry.get("type"))
    if spec is None:
        return Verdict("refuse", "Unknown action type.")
    blocked = spec.gate(entry.get("payload") or {}, entitlements, plan)
    if blocked:
        return Verdict("blocked", blocked)
    return Verdict("proceed")


async def execute_setup_action(conn, site: dict[str, Any], account: Any, entry: dict[str, Any]) -> dict[str, Any]:
    """Authoritative execute: re-resolves entitlements (never trusts the
    stage-time gate result — the plan may have changed since), re-runs the
    same gate, then runs the DB write. Caller must have already confirmed via
    `evaluate_setup_execute` returning 'proceed' — this does not repeat the
    same-turn/idempotency check, only the entitlement one, since that's the
    one thing that can legitimately change between stage and execute.

    Returns `{"ok", "status", "message", "result"?}` — never raises for an
    expected failure (gate block, `SetupActionError`); an unexpected
    exception from `spec.execute` propagates, matching the rest of the
    codebase's "don't swallow real bugs" convention.
    """
    spec = SETUP_ACTIONS_BY_NAME.get(entry["type"])
    if spec is None:
        return {"ok": False, "status": "blocked", "message": "Unknown action type."}
    ent = await resolve_entitlements(account.plan, conn=conn)
    blocked = spec.gate(entry["payload"], ent, account.plan)
    if blocked:
        return {"ok": False, "status": "blocked", "message": blocked}
    try:
        result = await spec.execute(conn, site, account, entry["payload"])
    except SetupActionError as exc:
        return {"ok": False, "status": "blocked", "message": str(exc)}
    return {
        "ok": True, "status": "executed", "result": result,
        "message": f"Done — {spec.summary(entry['payload'])}.",
    }


# ---------------------------------------------------------------------------
# Staged-entry helpers — pure closures for `store.mutate_staged_actions`.
# ---------------------------------------------------------------------------

def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def new_staged_entry(action_type: str, payload: dict[str, Any], summary: str) -> dict[str, Any]:
    return {
        "id": str(uuid4()), "type": action_type, "summary": summary, "payload": payload,
        "status": "proposed", "result": None, "message": None,
        "created_at": _now_iso(), "executed_at": None,
    }


def append_entry(entry: dict[str, Any]) -> Callable[[list[dict[str, Any]]], list[dict[str, Any]]]:
    def _fn(current: list[dict[str, Any]]) -> list[dict[str, Any]]:
        return [*current, entry]
    return _fn


def apply_outcome(entry_id: str, outcome: dict[str, Any]) -> Callable[[list[dict[str, Any]]], list[dict[str, Any]]]:
    """`outcome` is `execute_setup_action`'s return value.

    Only applies while the entry is still 'proposed' — same guard
    `dismiss_entry` uses. The real race guard is upstream of this function:
    both confirm callers (`routes/merlin_setup.py:_apply_action_outcome`,
    `services/merlin/setup_agent.py:do_execute_staged_action`) now hold a
    `merlin_store.lock_conversation_actions` row lock for the ENTIRE
    check-write-flip sequence, inside one transaction — so a second
    concurrent confirmation blocks on the lock and, once it acquires it,
    re-reads a status that is no longer 'proposed' and refuses before this
    closure ever runs twice for the same entry. This `status == 'proposed'`
    check is a defense-in-depth idempotency guard, not the sole race guard."""
    def _fn(current: list[dict[str, Any]]) -> list[dict[str, Any]]:
        out = []
        for e in current:
            if e.get("id") != entry_id or e.get("status") != "proposed":
                out.append(e)
                continue
            updated = dict(e)
            updated["status"] = outcome["status"]
            updated["message"] = outcome.get("message")
            if outcome["status"] == "executed":
                updated["result"] = outcome.get("result")
                updated["executed_at"] = _now_iso()
            out.append(updated)
        return out
    return _fn


def dismiss_entry(entry_id: str) -> Callable[[list[dict[str, Any]]], list[dict[str, Any]]]:
    def _fn(current: list[dict[str, Any]]) -> list[dict[str, Any]]:
        out = []
        for e in current:
            if e.get("id") == entry_id and e.get("status") == "proposed":
                e = {**e, "status": "dismissed"}
            out.append(e)
        return out
    return _fn


def find_entry(entries: Optional[list[dict[str, Any]]], entry_id: str) -> Optional[dict[str, Any]]:
    for e in entries or []:
        if e.get("id") == entry_id:
            return e
    return None
