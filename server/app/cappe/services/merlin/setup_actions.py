_MAX_BLOCKS_PER_ACTION = 12


def _validate_block(raw: Any) -> tuple[Optional[dict[str, Any]], Optional[str]]:
    if not isinstance(raw, dict):
        return None, "each block must be an object"
    btype = raw.get("type")
    # canvas is structural (grid/elements), not field-based — the concierge
    # doesn't build them (same reasoning as the v1 scope cut on canvas ops).
    if not isinstance(btype, str) or btype not in BLOCK_TYPES or btype == "canvas":
        return None, f"unsupported block type '{raw.get('type')}'"
    allowed = BLOCK_FIELDS.get(btype, {})
    content = {
        k: v for k, v in raw.items()
        if k != "type" and k in allowed and _field_value_error(v, allowed[k], btype, k) is None
    }
    return {"type": btype, **content}, None


def _validate_blocks(raw: Any) -> tuple[Optional[list[dict[str, Any]]], Optional[str]]:
    if raw is None:
        return [], None
    if not isinstance(raw, list) or not raw:
        return None, "'blocks' must be a non-empty list"
    if len(raw) > _MAX_BLOCKS_PER_ACTION:
        return None, f"at most {_MAX_BLOCKS_PER_ACTION} blocks per action"
    out: list[dict[str, Any]] = []
    for item in raw:
        block, err = _validate_block(item)
        if err:
            return None, err
        out.append(block)
    return out, None


def _gate_none(payload: dict[str, Any], entitlements: Entitlements, plan: str) -> Optional[str]:
    return None


