# ---------------------------------------------------------------------------
# set_promo — the FIRST server-side write gate on meta_config.promos. Today
# it's only ever hidden client-side (PromosPanel.tsx's `premium` prop); this
# is what makes the gate real.
# ---------------------------------------------------------------------------

_PROMO_TARGETS = frozenset({"bar", "popup"})
_PROMO_POSITIONS = frozenset({"top", "bottom"})
_PROMO_MODES = frozenset({"newsletter", "cta", "code"})


def _validate_set_promo(payload: dict[str, Any]) -> tuple[Optional[dict[str, Any]], Optional[str]]:
    if not isinstance(payload, dict):
        return None, "invalid payload"
    target = payload.get("target")
    if target not in _PROMO_TARGETS:
        return None, "'target' must be 'bar' or 'popup'"
    enabled = payload.get("enabled", True)
    if not isinstance(enabled, bool):
        return None, "'enabled' must be true or false"
    out: dict[str, Any] = {"target": target, "enabled": enabled}

    if target == "bar":
        text = payload.get("text")
        if enabled:
            if not isinstance(text, str) or not (1 <= len(text.strip()) <= 200):
                return None, "'text' must be 1-200 characters"
            text = text.strip()
        elif text is not None and not isinstance(text, str):
            return None, "'text' must be text"
        cta_label = payload.get("cta_label")
        if cta_label is not None and (not isinstance(cta_label, str) or len(cta_label) > 60):
            return None, "'cta_label' must be at most 60 characters"
        cta_href = payload.get("cta_href")
        if cta_href is not None and (not isinstance(cta_href, str) or len(cta_href) > 300):
            return None, "'cta_href' must be at most 300 characters"
        position = payload.get("position", "top")
        if position not in _PROMO_POSITIONS:
            return None, "'position' must be 'top' or 'bottom'"
        dismissible = payload.get("dismissible", True)
        if not isinstance(dismissible, bool):
            return None, "'dismissible' must be true or false"
        out.update(text=text, cta_label=cta_label, cta_href=cta_href, position=position, dismissible=dismissible)
    else:
        heading = payload.get("heading")
        if enabled:
            if not isinstance(heading, str) or not (1 <= len(heading.strip()) <= 120):
                return None, "'heading' must be 1-120 characters"
            heading = heading.strip()
        elif heading is not None and not isinstance(heading, str):
            return None, "'heading' must be text"
        body = payload.get("body")
        if body is not None and (not isinstance(body, str) or len(body) > 400):
            return None, "'body' must be at most 400 characters"
        mode = payload.get("mode", "newsletter")
        if mode not in _PROMO_MODES:
            return None, "'mode' must be 'newsletter', 'cta', or 'code'"
        cta_label = payload.get("cta_label")
        if cta_label is not None and (not isinstance(cta_label, str) or len(cta_label) > 60):
            return None, "'cta_label' must be at most 60 characters"
        out.update(heading=heading, body=body, mode=mode, cta_label=cta_label)

    return out, None


def _gate_set_promo(payload: dict[str, Any], entitlements: Entitlements, plan: str) -> Optional[str]:
    if is_premium_plan(plan):
        return None
    return (
        "Promo banners are a Pro/Business/Creator feature — your plan can't turn one on. "
        "Upgrade first, then ask me again and I'll set it up."
    )


def _summary_set_promo(payload: dict[str, Any]) -> str:
    label = "announcement bar" if payload["target"] == "bar" else "pop-up"
    action = "Enable" if payload["enabled"] else "Turn off"
    return f"{action} the {label} promo"


async def _execute_set_promo(conn, site: dict[str, Any], account: Any, payload: dict[str, Any]) -> dict[str, Any]:
    row = await conn.fetchrow(
        "SELECT meta_config FROM cappe_sites WHERE id = $1 FOR UPDATE", site["id"]
    )
    meta = loads(row["meta_config"]) if row else {}
    promos = meta.get("promos") if isinstance(meta.get("promos"), dict) else {}
    target = payload["target"]
    current = promos.get(target) if isinstance(promos.get(target), dict) else {}
    updated = dict(current)
    for key, value in payload.items():
        if key in ("target", "enabled") or value is None:
            continue
        updated[key] = value
    updated["enabled"] = payload["enabled"]
    meta = {**meta, "promos": {**promos, target: updated}}
    await conn.execute(
        "UPDATE cappe_sites SET meta_config = $2, updated_at = NOW() WHERE id = $1",
        site["id"], json.dumps(meta),
    )
    return {"target": target, "enabled": payload["enabled"]}


